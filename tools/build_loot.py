#!/usr/bin/env python3
"""Build Data/Loot.lua (drop chances for every creature) from the CMaNGOS
classic-db world database.

These are Classic 1.12 server values: a good baseline for Forever's old
content, but Forever can differ. The new Forever dungeons have no entries.

Usage:
  git clone --depth 1 https://github.com/cmangos/classic-db
  python tools/build_loot.py classic-db/Full_DB/ClassicDB_*.sql.gz

Output format (kept as strings so the game only parses what you look at):
  ns.Loot.items[itemID] = "<quality digit><item name>"
  ns.Loot.npcs[npcID]   = "itemID,chance[q];itemID,chance[q];..."
  ns.Loot.names[npcID]  = "Mob name" (for /ft loot <name>)
  chance is the drop percent, "q" marks a quest drop.
"""
import collections
import gzip
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from import_classic_stats import rows  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = (ROOT / "ForeverTactics" / "Data") if (ROOT / "ForeverTactics" / "ForeverTactics_Forever.toc").exists() else (ROOT / "Data")
MAX_PER_NPC = 20   # quest drops always kept on top of this
MAX_DEPTH = 3      # reference tables nested deeper than this are ignored


def expand(rows_, mult, out, refs, depth=0, fromref=False):
    """Add item -> [chance %, quest, from reference] for one loot table."""
    groups = collections.defaultdict(list)
    for r in rows_:
        groups[int(r["groupid"])].append(r)
    for g, rs in groups.items():
        if g == 0:
            share = None
        else:
            explicit = sum(abs(float(r["ChanceOrQuestChance"])) for r in rs)
            zero = [r for r in rs if float(r["ChanceOrQuestChance"]) == 0]
            share = max(0.0, 100 - explicit) / len(zero) if zero else 0.0
        for r in rs:
            raw = float(r["ChanceOrQuestChance"])
            ch = abs(raw) or (share or 0.0)
            m = int(r["mincountOrRef"])
            if m < 0:
                if depth < MAX_DEPTH:
                    rolls = max(1, int(r["maxcount"]))
                    expand(refs.get(-m, []), mult * ch / 100 * rolls, out, refs, depth + 1, True)
                continue
            e = out.setdefault(int(r["item"]), [0.0, raw < 0, fromref])
            e[0] += mult * ch
            e[2] = e[2] and fromref


def keep(item, quality, v):
    pct, quest, ref = v
    if quest:
        return True
    if quality == 0:          # grey junk: only common, mob specific drops
        return pct >= 5 and not ref
    if ref:                   # shared world drop tables: only notable ones
        return (pct >= 1 and quality >= 2) or (quality >= 3 and pct >= 0.05)
    return pct >= 0.5 or quality >= 3


def fmt(p):
    p = min(p, 100.0)
    if p >= 10:
        s = "%d" % round(p)
    elif p >= 1:
        s = "%.1f" % p
    else:
        s = "%.2f" % p
    return s.rstrip("0").rstrip(".") if "." in s else s


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(path):
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rt", encoding="utf-8", errors="replace") as fh:
        sql = fh.read()
    tmpl = rows(sql, "creature_template", key="Entry")
    clt = rows(sql, "creature_loot_template", key=None)
    rlt = rows(sql, "reference_loot_template", key=None)
    items = rows(sql, "item_template", key="entry")

    def table(rs):
        d = collections.defaultdict(list)
        for r in rs:
            d[int(r["entry"])].append(r)
        return d

    loot, refs = table(clt), table(rlt)
    npcs, used = {}, set()
    for entry, t in tmpl.items():
        lid = int(t.get("LootId") or 0)
        if not lid or lid not in loot:
            continue
        out = {}
        expand(loot[lid], 1.0, out, refs)
        kept = []
        for i, v in out.items():
            it = items.get(i)
            if it and keep(i, int(it["Quality"]), v):
                kept.append((i, v))
        if not kept:
            continue
        quest = [x for x in kept if x[1][1]]
        other = sorted((x for x in kept if not x[1][1]), key=lambda x: -x[1][0])[:MAX_PER_NPC]
        lst = sorted(quest + other, key=lambda x: (-x[1][0], x[0]))
        npcs[entry] = ";".join("%d,%s%s" % (i, fmt(v[0]), "q" if v[1] else "") for i, v in lst)
        used.update(i for i, _ in lst)

    lines = [
        "-- GENERATED by tools/build_loot.py from CMaNGOS classic-db. Do not edit.",
        "local _, ns = ...",
        "local I, N, M = {}, {}, {}",
        "ns.Loot = { items = I, npcs = N, names = M, source = \"cmangos-classic\" }",
    ]
    for i in sorted(used):
        it = items[i]
        lines.append("I[%d]=%s" % (i, lua_str(str(int(it["Quality"])) + it["name"])))
    for n in sorted(npcs):
        lines.append("N[%d]=%s" % (n, lua_str(npcs[n])))
    for n in sorted(npcs):
        lines.append("M[%d]=%s" % (n, lua_str(tmpl[n]["Name"])))
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "Loot.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    size = (OUT / "Loot.lua").stat().st_size
    print(f"Loot.lua: {len(npcs)} creatures, {len(used)} items, {size // 1024} KB")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
